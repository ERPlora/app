#!/usr/bin/env python3
"""Fails when a tracked code file is over the size cap of its language.

Caps, in physical lines (production / tests):

  Rust         500 outside the top-level `#[cfg(test)]` blocks, and 1000 for the whole file: past
               that, the tests move to `<module>/tests.rs`, a test file (1000)
  Kotlin       500 / 1000          Python      500 / 1000
  Shell        100 / 1500: a longer script is written in Python
  TypeScript   300 / 500 (and JavaScript)
  anything else (HTML, CSS, YAML, PowerShell, Java, Groovy)   1000 / 1500

Generated code (`gen/`, `autogenerated/`), documents and lockfiles are not measured.

The files over their cap are listed in `.file-size-allow` with their exact size, one per line as
`<ceiling> <path> <issue>`; a Rust source file takes `<production>/<whole file>`, "-" for a part
within its cap. A listed file may change but never grows past its ceiling, and the change that
shrinks it lowers the ceiling to the new size. The list only shrinks: against the commit where HEAD
leaves `origin/main` (their merge-base, so a release of an older tag keeps the ceilings it was built
with) it gains no path and raises no ceiling. The one way in is a lower cap: what that commit
already had over today's cap may be listed at most at its size there.

Usage: file-size.py [checkout] [main]   (defaults: the current directory, origin/main)
Exit:  0 within the caps · 1 a file or a list line breaks them, one line each
       2 cannot judge: not a git checkout, main is missing or shares no history with HEAD, or the
         list is malformed
"""

from __future__ import annotations

import os
import re
import subprocess
import sys
from typing import Dict, List, Optional, Tuple

LIST = ".file-size-allow"
CODE = re.compile(r"\.(rs|kt|kts|java|gradle|ts|tsx|js|jsx|mjs|cjs|sh|html|css|py|ps1|yml)$")
GENERATED = re.compile(r"(^|/)(gen|autogenerated)/")
TEST = re.compile(r"(^|/)(tests?|android-tests)/|\.test\.[A-Za-z]+$|(^|/)tests\.rs$")
ISSUE = re.compile(r"^[A-Za-z0-9_./-]*#[0-9]+$")

SCRIPT_CAPS = (300, 500)
OTHER_CAPS = (1000, 1500)
# Production and test cap of each measured suffix.
CAPS = {
    "rs": (500, 1000),
    "kt": (500, 1000),
    "kts": (500, 1000),
    "py": (500, 1000),
    "sh": (100, 1500),
    "ts": SCRIPT_CAPS,
    "tsx": SCRIPT_CAPS,
    "js": SCRIPT_CAPS,
    "jsx": SCRIPT_CAPS,
    "mjs": SCRIPT_CAPS,
    "cjs": SCRIPT_CAPS,
    "java": OTHER_CAPS,
    "gradle": OTHER_CAPS,
    "html": OTHER_CAPS,
    "css": OTHER_CAPS,
    "ps1": OTHER_CAPS,
    "yml": OTHER_CAPS,
}
RUST_WHOLE_CAP = 1000

HINT = """
A file over its cap is split by responsibility, in a pull request of its own that only moves code;
a shell script past its cap is written in Python. A listed file may change without being split, but
never grows past its ceiling: what a change adds goes to a new module. When it shrinks, its ceiling
comes down to its exact size, and a new file never joins the list.
"""


class Unjudgeable(Exception):
    """The check cannot judge this checkout; exits 2."""


class Part:
    """One measured part of a file against its cap: the whole file, or a Rust file's production."""

    def __init__(self, value: int, cap: int, label: str, cap_name: str) -> None:
        self.value = value
        self.cap = cap
        self.label = label
        self.cap_name = cap_name

    def over_cap(self) -> str:
        return f"{self.value} {self.label}, over the {self.cap_name} cap of {self.cap}"


Ceiling = List[Optional[int]]  # one number per part, None for "-"


def is_rust_source(path: str) -> bool:
    return path.endswith(".rs") and not TEST.search(path)


def cap_of(path: str) -> int:
    production, tests = CAPS[path.rsplit(".", 1)[1]]
    return tests if TEST.search(path) else production


def line_count(data: bytes) -> int:
    """Lines as a text tool counts them: a last line without its newline counts too."""
    return data.count(b"\n") + (1 if data and not data.endswith(b"\n") else 0)


def rust_test_lines(data: bytes) -> int:
    """The lines of the top-level `#[cfg(test)]` items: the attribute, the attributes and comments
    after it, and the item up to its closing brace at column 0 (or its `;`)."""
    lines = data.split(b"\n")[: line_count(data)]
    state, count = "code", 0
    for line in lines:
        if state == "code":
            if line.startswith(b"#[cfg(test)]"):
                state, count = "attribute", count + 1
            continue
        count += 1
        if state == "body":
            state = "code" if line.startswith(b"}") else "body"
        else:
            state = after_attribute(line)
    return count


def after_attribute(line: bytes) -> str:
    """Where a line after `#[cfg(test)]` leaves the item it gates."""
    if not line.strip(b" \t") or line.startswith(b"#") or line.lstrip(b" \t").startswith(b"//"):
        return "attribute"
    end = line.rstrip(b" \t")
    if end.endswith(b"{"):
        return "body"
    return "code" if end.endswith((b";", b"}")) else "attribute"


def parts_of(path: str, data: bytes) -> List[Part]:
    whole = line_count(data)
    if is_rust_source(path):
        return [
            Part(whole - rust_test_lines(data), cap_of(path), "production lines", "production"),
            Part(whole, RUST_WHOLE_CAP, "lines in all", "whole-file"),
        ]
    return [Part(whole, cap_of(path), "lines", "tests" if TEST.search(path) else "production")]


def git(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", *args], capture_output=True, check=False)


def git_text(*args: str) -> Optional[str]:
    done = git(*args)
    return done.stdout.decode().strip() if done.returncode == 0 else None


def tracked_parts() -> Dict[str, List[Part]]:
    listing = git("ls-files", "-z").stdout.decode()
    measured = {}
    for path in listing.split("\0"):
        if not CODE.search(path) or GENERATED.search(path):
            continue
        try:
            with open(path, "rb") as handle:
                measured[path] = parts_of(path, handle.read())
        except OSError:
            continue  # tracked but deleted in the working tree: nothing to measure
    return measured


def parts_at(commit: str, path: str) -> Optional[List[Part]]:
    shown = git("cat-file", "blob", f"{commit}:{path}")
    return parts_of(path, shown.stdout) if shown.returncode == 0 else None


def parse_ceiling(text: str) -> Optional[Ceiling]:
    tokens = text.split("/")
    if len(tokens) > 2 or text == "-/-" or (len(tokens) == 1 and text == "-"):
        return None
    if not all(token == "-" or token.isdigit() for token in tokens):
        return None
    return [None if token == "-" else int(token) for token in tokens]


def show_ceiling(ceiling: Ceiling) -> str:
    return "/".join("-" if value is None else str(value) for value in ceiling)


def line_problem(fields: List[str], seen: Dict[str, Ceiling]) -> Optional[str]:
    if len(fields) != 3:
        return "expected <ceiling> <path> <issue>"
    ceiling = parse_ceiling(fields[0])
    if ceiling is None:
        return "the ceiling is a number, or <production>/<whole> for Rust"
    if not ISSUE.match(fields[2]):
        return "the third field is the issue, app#N"
    if fields[1] in seen:
        return "the path is listed twice"
    return shape_problem(fields[1], ceiling)


def shape_problem(path: str, ceiling: Ceiling) -> Optional[str]:
    if len(ceiling) == 2 and not is_rust_source(path):
        return "only a Rust source file takes <production>/<whole>"
    if len(ceiling) == 1 and is_rust_source(path):
        return "a Rust source file takes <production>/<whole>, - for a part within its cap"
    return None


def read_list(text: str) -> Tuple[Dict[str, Ceiling], List[str]]:
    """``({path: ceiling}, malformed lines)``; blank lines and `#` comments are skipped."""
    ceilings: Dict[str, Ceiling] = {}
    malformed = []
    for number, line in enumerate(text.splitlines(), 1):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        fields = line.split()
        problem = line_problem(fields, ceilings)
        if problem:
            malformed.append(f"::error file={LIST},line={number}::{problem} ({line})")
        else:
            ceilings[fields[1]] = parse_ceiling(fields[0])
    return ceilings, malformed


def base_ceilings(text: str) -> Dict[str, Ceiling]:
    """The list as the base has it, without judging it: only usable ceilings are kept."""
    ceilings = {}
    for line in text.splitlines():
        fields = line.split()
        if len(fields) >= 2 and not line.lstrip().startswith("#"):
            ceiling = parse_ceiling(fields[0])
            if ceiling is not None:
                ceilings[fields[1]] = ceiling
    return ceilings


def unlisted_problems(parts: List[Part]) -> List[str]:
    return [part.over_cap() for part in parts if part.value > part.cap]


def part_problem(part: Part, ceiling: Optional[int]) -> Optional[str]:
    if ceiling is None:
        return part.over_cap() if part.value > part.cap else None
    if part.value > ceiling:
        return f"{part.value} {part.label}, over its ceiling of {ceiling}"
    if part.value > part.cap and ceiling > part.value:
        return f"ceiling {ceiling} is loose for {part.value} {part.label}: lower it to {part.value}"
    return None


def listed_problems(parts: List[Part], ceiling: Ceiling) -> List[str]:
    problems = [p for p in (part_problem(part, c) for part, c in zip(parts, ceiling)) if p]
    if all(part.value <= part.cap for part in parts):
        if len(parts) == 1:
            return problems + [f"{parts[0].value} lines fit under the cap of {parts[0].cap}: remove it from {LIST}"]
        production, whole = parts
        return problems + [
            f"{production.value} production lines and {whole.value} in all fit under the caps: remove it from {LIST}"
        ]
    return problems + [
        f"{part.value} {part.label} fit under the cap of {part.cap}: write - for that part"
        for part, c in zip(parts, ceiling)
        if c is not None and part.value <= part.cap
    ]


def size_problems(measured: Dict[str, List[Part]], ceilings: Dict[str, Ceiling]) -> List[Tuple[str, str]]:
    problems = []
    for path, parts in measured.items():
        found = listed_problems(parts, ceilings[path]) if path in ceilings else unlisted_problems(parts)
        problems += [(path, problem) for problem in found]
    problems += [
        (path, f"listed in {LIST} but not tracked: remove the line") for path in ceilings if path not in measured
    ]
    return problems


def allowed_ceiling(listed: Optional[Ceiling], base_parts: Optional[List[Part]], width: int) -> Ceiling:
    """The highest ceiling the base lets a path have: its own ceiling there, or, for a part the base
    already had over today's cap, its size there."""
    allowed: Ceiling = []
    for index in range(width):
        candidates = []
        if listed is not None and len(listed) == width and listed[index] is not None:
            candidates.append(listed[index])
        if base_parts is not None and base_parts[index].value > base_parts[index].cap:
            candidates.append(base_parts[index].value)
        allowed.append(max(candidates) if candidates else None)
    return allowed


def raises(ceiling: Ceiling, allowed: Ceiling) -> bool:
    return any(now is not None and (most is None or now > most) for now, most in zip(ceiling, allowed))


def ratchet_problems(
    ceilings: Dict[str, Ceiling], base_list: Dict[str, Ceiling], base: str, base_label: str
) -> List[Tuple[str, str]]:
    problems = []
    for path, ceiling in ceilings.items():
        allowed = allowed_ceiling(base_list.get(path), parts_at(base, path), len(ceiling))
        if all(most is None for most in allowed):
            problems.append((path, f"new exception, not in the {LIST} of {base_label}"))
        elif raises(ceiling, allowed):
            problems.append((path, f"raises its ceiling from {show_ceiling(allowed)} to {show_ceiling(ceiling)}"))
    return problems


def merge_base(main: str) -> str:
    if git("rev-parse", "--verify", "--quiet", f"{main}^{{commit}}").returncode != 0:
        raise Unjudgeable(
            f"{main} is not in this checkout: run git fetch origin main (the list can only shrink against it)"
        )
    base = git_text("merge-base", "HEAD", main)
    if base is None:
        raise Unjudgeable(
            f"HEAD and {main} share no history in this checkout: fetch the whole history "
            "(git fetch --unshallow origin) so the list has a base to shrink against"
        )
    return base


def read_working_list() -> str:
    try:
        with open(LIST, encoding="utf-8") as handle:
            return handle.read()
    except FileNotFoundError:
        return ""


def judge(main: str) -> int:
    base = merge_base(main)
    base_label = f"{main}@{git_text('rev-parse', '--short', base)}"
    ceilings, malformed = read_list(read_working_list())
    if malformed:
        print("\n".join(malformed))
        return 2
    problems = size_problems(tracked_parts(), ceilings)
    base_list = git("cat-file", "blob", f"{base}:{LIST}")
    if base_list.returncode == 0:
        problems += ratchet_problems(ceilings, base_ceilings(base_list.stdout.decode()), base, base_label)
    else:
        # Only true on the commit that brings the list: after it, the base always has one.
        print(f"{base_label} has no {LIST}: the ratchet starts with this list")
    for path, problem in problems:
        print(f"::error file={path}::{path}: {problem}")
    if problems:
        sys.stdout.flush()
        print(HINT, file=sys.stderr)
        return 1
    print(f"every tracked code file is within its cap, or within its ceiling in {LIST}")
    return 0


def main(argv: List[str]) -> int:
    root = argv[1] if len(argv) > 1 else "."
    main_ref = argv[2] if len(argv) > 2 else "origin/main"
    top = subprocess.run(["git", "-C", root, "rev-parse", "--show-toplevel"], capture_output=True, check=False)
    if top.returncode != 0:
        print(f"::error::{root} is not a git checkout", file=sys.stderr)
        return 2
    try:
        os.chdir(top.stdout.decode().strip())
        return judge(main_ref)
    except Unjudgeable as error:
        print(f"::error::{error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
